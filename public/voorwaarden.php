  <h2>Artikel 1 – Definities</h2>
  <ol>
    <li>Onder “verkoper” wordt verstaan: Publicaties Soedamah.</li>
    <li>Onder “koper” wordt verstaan: iedere natuurlijke of rechtspersoon die een boek of e-book bestelt.</li>
    <li>Onder “producten” worden verstaan: papieren boeken, e-books en overige digitale publicaties.</li>
  </ol>

  <h2>Artikel 2 – Toepasselijkheid</h2>
  <ol>
    <li>Deze algemene voorwaarden zijn van toepassing op alle aanbiedingen, bestellingen en overeenkomsten.</li>
    <li>Door een bestelling te plaatsen verklaart de koper met deze voorwaarden akkoord te gaan.</li>
  </ol>

  <h2>Artikel 3 – Totstandkoming van de overeenkomst</h2>
  <ol>
    <li>De overeenkomst komt tot stand zodra de bestelling is bevestigd en de betaling is ontvangen.</li>
    <li>De verkoper behoudt zich het recht voor een bestelling te weigeren indien daarvoor een gegronde reden bestaat.</li>
  </ol>

  <h2>Artikel 4 – Prijzen en betaling</h2>
  <ol>
    <li>Alle vermelde prijzen zijn in euro's.</li>
    <li>Betaling dient vooraf plaats te vinden via de aangeboden betaalmethoden.</li>
    <li>Pas na ontvangst van de betaling wordt het product geleverd.</li>
  </ol>

  <h2>Artikel 5 – Levering</h2>
  <ol>
    <li>Papieren boeken worden zo spoedig mogelijk verzonden.</li>
    <li>E-books worden na succesvolle betaling digitaal beschikbaar gesteld of per e-mail toegezonden.</li>
    <li>Opgegeven levertijden zijn indicatief.</li>
  </ol>

  <h2>Artikel 6 – Herroepingsrecht</h2>
  <ol>
    <li>Voor papieren boeken geldt het wettelijke herroepingsrecht van veertien (14) dagen, tenzij een wettelijke uitzondering van toepassing is.</li>
    <li>Voor digitale producten (e-books) vervalt het herroepingsrecht zodra de levering is begonnen en de koper vooraf uitdrukkelijk heeft ingestemd met onmiddellijke levering en afstand heeft gedaan van het herroepingsrecht.</li>
  </ol>

  <h2>Artikel 7 – Auteursrecht</h2>
  <ol>
    <li>Alle auteursrechten en overige intellectuele eigendomsrechten blijven berusten bij de auteur of rechthebbende.</li>
    <li>Het is niet toegestaan een e-book of ander digitaal product geheel of gedeeltelijk te kopiëren, verspreiden, publiceren, door te sturen, uploaden of op andere wijze aan derden beschikbaar te stellen zonder voorafgaande schriftelijke toestemming.</li>
    <li>De aangekochte publicatie is uitsluitend bestemd voor persoonlijk gebruik.</li>
  </ol>

  <h2>Artikel 8 – Retourneren</h2>
  <ol>
    <li>Papieren boeken kunnen binnen de wettelijke termijn worden geretourneerd, mits zij onbeschadigd zijn.</li>
    <li>De kosten van retourzending komen voor rekening van de koper, tenzij de wet anders bepaalt.</li>
    <li>E-books kunnen na levering niet worden geretourneerd.</li>
  </ol>

  <h2>Artikel 9 – Aansprakelijkheid</h2>
  <ol>
    <li>De aansprakelijkheid van de verkoper is beperkt tot het bedrag van de aankoopprijs van het betreffende product.</li>
    <li>De verkoper is niet aansprakelijk voor indirecte schade, gevolgschade of gederfde winst, tenzij sprake is van opzet of bewuste roekeloosheid.</li>
  </ol>

  <h2>Artikel 10 – Klachten</h2>
  <ol>
    <li>Klachten kunnen schriftelijk of per e-mail worden ingediend.</li>
    <li>De verkoper streeft ernaar klachten binnen veertien (14) dagen te behandelen.</li>
  </ol>

  <h2>Artikel 11 – Privacy</h2>
  <p>Persoonsgegevens worden verwerkt overeenkomstig de geldende privacywetgeving en de
