  <h2>Artikel 12 – Overmacht</h2>
  <p>De verkoper is niet aansprakelijk voor vertragingen of tekortkomingen die het gevolg zijn van
     overmacht, waaronder storingen bij internet-, betalings- of bezorgdiensten.</p>

  <h2>Artikel 13 – Toepasselijk recht</h2>
  <p>Op alle overeenkomsten is uitsluitend Nederlands recht van toepassing.</p>

  <h2>Artikel 14 – Bevoegde rechter</h2>
  <p>Geschillen worden voorgelegd aan de bevoegde rechter in Nederland, tenzij dwingendrechtelijke
     bepalingen anders voorschrijven.</p>

